// 05 Multiply and Assign *=
// Start with the given value, then use *= to update it:

// 01 A population of a town is 5,000. It becomes 3 times larger. Use *= to update the population and print it.
// 02 A factory produces 120 units per day. Production becomes 4 times due to new machines. Use *= to update the daily production and print it.
// 03 A savings amount is ₹2,000. It doubles (becomes 2 times). Use *= to update the amount and print it.
// 04 A garden has 50 plants. After a season, the number of plants becomes 5 times. Use *= to update the total plants and print it.
// 05 A game score is 150. A bonus multiplies the score by 3. Use *= to update the score and print it.
// # Problem 1: Update town population
population = 5000
population *= 3
print("Updated Population:", population)

// # Problem 2: Update factory daily production
daily_production = 120
daily_production *= 4
print("Updated Daily Production:", daily_production, "units")

// # Problem 3: Update savings amount
savings = 2000
savings *= 2
print("Updated Savings: ₹", savings, sep="")

// # Problem 4: Update total garden plants
garden_plants = 50
garden_plants *= 5
print("Updated Total Plants:", garden_plants)

// # Problem 5: Update game score with a bonus
game_score = 150
game_score *= 3
print("Updated Score:", game_score, "points")
