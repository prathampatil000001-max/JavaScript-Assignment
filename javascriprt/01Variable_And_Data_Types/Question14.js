// 2. Add and Assign +=
// Start with the given value, then use += to update it:

// A student has 200 marks. He gets 35 more marks. Use += to update the total and print it.
// A savings account has ₹5,000. ₹1,200 is deposited. Use += to update the balance and print it.
// A phone battery is at 45%. It gets charged by 30%. Use += to update the battery percentage and print it.
// A game player has 1,250 points. He earns 375 more points. Use += to update the score and print it.
// A library has 840 books. 160 new books are added. Use += to update the total number of books and print it.

// Problem 1: Update student marks
let totalMarks = 200;
totalMarks += 35;
console.log("Updated Marks: " + totalMarks);

// Problem 2: Update savings account balance
let accountBalance = 5000;
accountBalance += 1200;
console.log("Updated Balance: ₹" + accountBalance);

// Problem 3: Update phone battery percentage
let batteryPercentage = 45;
batteryPercentage += 30;
console.log("Updated Battery: " + batteryPercentage + "%");

// Problem 4: Update game player points
let playerPoints = 1250;
playerPoints += 375;
console.log("Updated Score: " + playerPoints + " points");

// Problem 5: Update total library books
let totalBooks = 840;
totalBooks += 160;
console.log("Updated Total Books: " + totalBooks);
