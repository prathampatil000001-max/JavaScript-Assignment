// 3. Multiplication *
// Write a JavaScript program to solve each problem:

// Q01 One notebook costs ₹45. Calculate the cost of buying 8 notebooks.
// Q02 A machine produces 120 bottles per hour. Calculate its production in 6 hours.
// Q03 A garden has 7 rows with 15 plants in each row. Find the total number of plants.
// Problem 1: Cost of Notebooks
let notebookCost = 45;
let totalNotebooks = 8;
let totalCost = notebookCost * totalNotebooks;

console.log("Total cost for 8 notebooks: ₹" + totalCost);


// Problem 2: Machine Bottle Production
let bottlesPerHour = 120;
let totalHours = 6;
let totalProduction = bottlesPerHour * totalHours;

console.log("Total bottles produced in 6 hours: " + totalProduction);


// Problem 3: Total Plants in a Garden
let totalRows = 7;
let plantsPerRow = 15;
let totalPlants = totalRows * plantsPerRow;

console.log("Total number of plants in the garden: " + totalPlants);
