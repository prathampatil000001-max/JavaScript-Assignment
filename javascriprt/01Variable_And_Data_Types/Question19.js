// Exponentiation and Assign **=
// A square garden has side 10 m; find its area using **=.
// A cube box has edge 4 cm; find its volume using **=.
// An image’s size factor is 3; find the total area growth factor using **=.

// # Problem 1: Area of a square garden (side^2)
side = 10
side **= 2
print("Area of the garden:", side, "sq. m")

// # Problem 2: Volume of a cube box (edge^3)
edge = 4
edge **= 3
print("Volume of the box:", edge, "cu. cm")

// # Problem 3: Total area growth factor (factor^2)
growth_factor = 3
growth_factor **= 2
print("Total area growth factor:", growth_factor)
