// 05 Divide and Assign /=
// Start with the given value, then use /= to update it:

// 01 A total of 1,200 metres of cloth is divided equally into 4 parts. Use /= to update the length of one part and print it.
// 02 A company has ₹80,000 budget. It is divided equally among 8 projects. Use /= to update the budget per project and print it.
// 03 A jar has 960 grams of sugar. It is divided equally into 6 packets. Use /= to update the sugar in one packet and print it.
// 04 A distance of 450 km is covered in 5 equal trips. Use /= to update the distance per trip and print it.
// 05 A total of 2,500 marks is divided equally among 10 students. Use /= to update the marks per student and print it.

// # Problem 1: Length of one cloth part
cloth_length = 1200
cloth_length /= 4
print("Length of one part:", cloth_length, "metres")

// # Problem 2: Budget per project
total_budget = 80000
total_budget /= 8
print("Budget per project: ₹", total_budget, sep="")

// # Problem 3: Sugar in one packet
sugar_weight = 960
sugar_weight /= 6
print("Sugar in one packet:", sugar_weight, "grams")

// # Problem 4: Distance per trip
total_distance = 450
total_distance /= 5
print("Distance per trip:", total_distance, "km")

// # Problem 5: Marks per student
total_marks = 2500
total_marks /= 10
print("Marks per student:", total_marks)
